package subgroupchain

import (
	"github.com/dianpeng/layoutalgebra/internal/check"
)

type Range interface {
	IsUnknown() bool
	IsInterval() bool
}

type RangeUnknown struct{}

type RangeInterval struct {
	upperBound Value
}

func (self *RangeUnknown) IsUnknown() bool  { return true }
func (self *RangeUnknown) IsInterval() bool { return false }

func (self *RangeInterval) IsUnknown() bool   { return false }
func (self *RangeInterval) IsInterval() bool  { return true }
func (self *RangeInterval) UpperBound() Value { return self.upperBound }

func NewUnknown() Range { return &RangeUnknown{} }
func NewInterval(ub Value) Range {
	return &RangeInterval{upperBound: ub}
}

// --------------------------------------------------------------------------------------
//
// calculation supported by range
//
// Notes the expression that requires re-project variable to specific set of needed
// ranges will be as following
//
// (1) Div, this is mainly used for splitting a variable
//
//     For range: this result in [0, upper(a)/divider)
//
// (2) Mod, same as (2)
//
//     For range: this result in[0, modvalue) for example v % 32 => v <- [0, 32)
//
// (3) Mul/Add, this is the complicated part
//
//     Our framework will generate **strided mapping back to 1D offset**, this will
//     make, assume i, j are variables with its own range, and the 1D offset will be
//     offset = i * stride + j. This effectively forms 2 components i * stride and j
//     1) i * stride is typically a sub-group, since i will be [0, K), and stride is
//        a constant, hence result in set [0, stride, 2 * stride, ..., (K-1) * stride)
//
//     2) the j is a set of coset, which is generated by modular result
//
//     3) 1) and 2) forms a full transversal of the full domain [0, k * stride)
//
//     But this is too expensive to model in our code, since we have to introduce lots
//     of abstract algebra structure for modeling various shapes of domain, ie range
//     and all are not simple consequtive ranges, like the strided sub-groups. Hence
//     to simplify our life, we introduce a new expression, called Stride, which is
//     essentially Stride(i[k], stride[k]) = dotprod (i, stride). The stride is essentially
//     classical stride array. This Stride can simplify the range analysis directly for
//     our needed one, ie the Stride operation must be working on a shape [m0][m1]...[mu-1]
//     hence we are sure its range is full [0, PI(mi))
//
//     Another thing, our folding rule will not try to hoist Mul + Add into Stride or
//     vice versa. Stride is generated at known callsite, ie it is a special instruction
//     which is opaque to the framework, but just for simplifying our analysis
//
// (4) Rest operation can be viewea as result in unknown range
//
// Basically the above forms a simple data flow analysis, ie a monotone lattice
//
// - Top: (-inf, inf)
// - Bottom: unknown
// - Transfer function:
//   - Variable: directly yield its range
//   - Binary: Mul/Div/Mod, yield new range accordingly
//   - Others: unknown
//
// --------------------------------------------------------------------------------------

func (self *RangeInterval) Mul(that *RangeInterval) *RangeInterval {
	return &RangeInterval{
		upperBound: self.UpperBound() * that.UpperBound(),
	}
}

func (self *RangeInterval) Div(that *Const) *RangeInterval {
	// v in [0, U) => v/d in [0, ceil(U/d))
	d := that.Value()
	return &RangeInterval{
		upperBound: (self.UpperBound() + d - 1) / d,
	}
}

func (self *RangeInterval) Mod(that *Const) *RangeInterval {
	// v in [0, U) => v % m == v when m >= U, else v % m in [0, m)
	ub := self.UpperBound()
	if m := that.Value(); m < ub {
		ub = m
	}
	return &RangeInterval{
		upperBound: ub,
	}
}

// A simple data-flow algorithm that performs range analysis. We run a post-order walk
// on expression tree.
func AnalyzeRange(root Expr) {
	VisitPost(
		root,
		func(Expr) bool { return true },
		func(n Expr) error {
			switch node := n.(type) {
			default:
				check.Unreachable()
				return nil

			case *Const:
				node.SetRange(NewUnknown())
				return nil

			case *Symbol:
				node.SetRange(NewUnknown())
				return nil

			case *Variable:
				node.SetRange(NewInterval(node.UpperBound()))
				return nil

			case *Coordinate:
				// a Coordinate is a factorization digit with a compile-known
				// bound cached on the node; its value subtree is visited on
				// its own, but the node's range comes from the cached bound
				node.SetRange(NewInterval(node.UpperBound()))
				return nil

			case *Stride:
				// this is a special node to perform stride operation, otherwise we will have
				// to model coset + sub-group as part of the range analysis, and also this
				// does not sounds simple at all, and also general sub-group coset does not
				// always guarantee a fully consqutive ranges, which is totally a overkill
				// for us. Stride is generated as is during the transformation, and the upper
				// layer just know what it is doing. And implicitly the stride has a flatten
				// 1D iteration space, that it exhausts fully. Notes the 1D iteration space
				// does not have to map to offset space, since it is not always used for
				// memory access
				node.SetRange(NewInterval(node.Rank()))
				return nil

			case *Binary:
				lRng := node.L().Range()

				// Div/Mod only produce a known interval when the left side is an
				// interval and the right side is a positive constant divider
				rConst, rIsConst := node.R().(*Const)
				lIt, lIsIt := lRng.(*RangeInterval)

				switch node.Op() {
				case Div:
					if rIsConst && rConst.Value() > 0 && lIsIt {
						node.SetRange(lIt.Div(rConst))
					} else {
						node.SetRange(NewUnknown())
					}

				case Mod:
					if rIsConst && rConst.Value() > 0 && lIsIt {
						node.SetRange(lIt.Mod(rConst))
					} else {
						node.SetRange(NewUnknown())
					}

				default:
					node.SetRange(NewUnknown())
				}
				return nil
			}
		},
	)
}

// helper function
func MustGetUpperBound(x Expr) int {
	rng := x.Range()
	check.CheckNotNil(rng, "expression has no range attached")
	check.Check(rng.IsInterval(), "expression range is not an interval")
	return int(rng.(*RangeInterval).UpperBound())
}
